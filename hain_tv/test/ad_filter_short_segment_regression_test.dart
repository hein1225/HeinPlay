    final filter = M3u8AdFilter();
    final content = buildPlaylist(count: 100);
    final result = filter.purify(baseUrl, content, cleanDiscontinuities: true);
    expect(segmentUrlsOf(result!).length, 100);
  });

  test('同目录下的真广告分片仍会被清理（修复没有打掉广告能力）', () {
    final filter = M3u8AdFilter();
    final urls = <String>[];
    for (var i = 0; i < 40; i++) {
      // 每 10 段插 1 段同目录广告（文件名前缀不同 → 归一化后能区分）
      urls.add(i == 20 ? '$segDir/ad12.ts' : '$segDir/plist\$i.ts');
