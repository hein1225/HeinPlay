    List<String>? overrideUrls,
  }) {
    final sb = StringBuffer();
    sb.writeln('#EXTM3U');
    sb.writeln('#EXT-X-VERSION:3');
    sb.writeln('#EXT-X-TARGETDURATION:10');
    sb.writeln('#EXT-X-MEDIA-SEQUENCE:0');
    sb.writeln(
