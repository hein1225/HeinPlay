    );
    for (var i = 0; i < count; i++) {
      final d = realDurations[i % realDurations.length];
      sb.writeln('#EXTINF:${d.toStringAsFixed(6)},');
      final url = (overrideUrls != null && i < overrideUrls.length)
          ? overrideUrls[i]
          : '$segDir/plist\$i.ts';
      sb.writeln(url);
    }
    sb.writeln('#EXT-X-ENDLIST');
    return sb.toString();
  }

  List<String> segmentUrlsOf(String playlist) {
    return playlist
        .split('\n')
        .map((l) => l.trim())
        .where((l) => l.isNotEmpty && !l.startsWith('#'))
        .toList();
  }

