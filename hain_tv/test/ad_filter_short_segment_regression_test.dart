    final content = buildPlaylist(count: 40, overrideUrls: urls);
    final result = filter.purify(baseUrl, content, cleanDiscontinuities: true);
    final after = segmentUrlsOf(result!);
    expect(after.length, lessThan(40), reason: '广告段应被删除');
    expect(after.any((u) => u.contains('ad12.ts')), isFalse);
