/// 【为什么自己写而不引三方库】
///   本工程只构建 Android，且此处**仅在产物内部**使用（代理读 PTS 用）。
///   引 `pointycastle` 会新增一个较大的依赖树（且需改 pubspec + 走网络拉包），
