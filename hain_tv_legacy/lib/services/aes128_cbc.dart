///   MPEG-TS 的 0x47 sync byte（188 栅格命中率仅随机噪声水平），
///   因此必须解出一份明文才能解析首个视频 PES 的 PTS。
///
/// 【安全边界】本实现**不用于保密**，只用于把公开的流媒体分片解成明文以读
///   时间戳。密钥来自公开的 `key.key`（HLS 规范如此），不涉及任何私密数据。
