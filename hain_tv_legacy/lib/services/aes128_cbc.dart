  /// AES-128 轮常量。
  static const List<int> _rcon = <int>[
    0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36,
  ];

  // ── GF(2^8) 乘法 ────────────────────────────────────────────────────────

  static int _xtime(int x) => ((x << 1) ^ ((x & 0x80) != 0 ? 0x1b : 0)) & 0xff;

  static int _mul(int a, int b) {
    var r = 0;
    var x = a & 0xff;
    var y = b & 0xff;
    while (y != 0) {
      if ((y & 1) != 0) r ^= x;
      x = _xtime(x);
      y >>= 1;
    }
    return r & 0xff;
  }

  // ── 🔴 InvMixColumns 预计算表（2026-10-12 性能修复）─────────────────────
  //
  // 【问题】原实现的 `_invMixColumns` 每列调 16 次 `_mul()`，而 `_mul` 是
  //   **运行时位循环**（最多 8 次迭代 + `_xtime`）。于是一个 16 字节块要
  //   4 列 × 16 次 × ~8 轮 = 约 512 次循环迭代，再 × 9 轮解密 ≈ 4600 次。
  //   实测吞吐仅 **1.03 MB/s**，一个 300KB 的分片要解 283ms，加上回源与
  //   转发，播放器表现为「一卡一卡、基本没缓冲」。
  //
  // 【修法】GF(2^8) 乘法只有 256×256 种输入组合，且 InvMixColumns 的四个
  //   系数固定（0x0e/0x0b/0x0d/0x09），故直接预计算 4 张 256 项查表，
  //   运行时 O(1)。这与工业实现（T-table / OpenSSL）同思路。
  //
  // 【实测】306080 字节：283ms → 见 tool/aes_bench.dart。
  static final Uint8List _mul0e = _buildMulTable(0x0e);
  static final Uint8List _mul0b = _buildMulTable(0x0b);
  static final Uint8List _mul0d = _buildMulTable(0x0d);
  static final Uint8List _mul09 = _buildMulTable(0x09);

  static Uint8List _buildMulTable(int coeff) {
    final t = Uint8List(256);
    for (var i = 0; i < 256; i++) {
      t[i] = _mul(i, coeff);
    }
    return t;
  }

  // ── 密钥扩展（AES-128：11 轮密钥 = 176 字节）──────────────────────────

  /// 把 16 字节密钥扩展为 11 组轮密钥（每组 16 字节，共 176 字节）。
  static Uint8List _expandKey(Uint8List key) {
    if (key.length != 16) {
      throw ArgumentError('AES-128 需要 16 字节密钥，实际 ${key.length}');
    }
    final w = Uint8List(176);
    w.setRange(0, 16, key);
    var bytesGenerated = 16;
    var rconIter = 1;
    final t = Uint8List(4);
    while (bytesGenerated < 176) {
      t.setRange(0, 4, w, bytesGenerated - 4);
      if (bytesGenerated % 16 == 0) {
        // RotWord
        final tmp = t[0];
        t[0] = t[1];
        t[1] = t[2];
        t[2] = t[3];
        t[3] = tmp;
        // SubWord
        for (var i = 0; i < 4; i++) {
          t[i] = _sbox[t[i]];
        }
        t[0] ^= _rcon[rconIter];
        rconIter++;
      }
      for (var i = 0; i < 4; i++) {
        w[bytesGenerated] = w[bytesGenerated - 16] ^ t[i];
        bytesGenerated++;
      }
    }
    return w;
  }

  // ── 单块解密 ───────────────────────────────────────────────────────────

  static void _invSubBytes(Uint8List s) {
    for (var i = 0; i < 16; i++) {
      s[i] = _rsbox[s[i]];
    }
  }

  static void _invShiftRows(Uint8List s) {
    // 状态按列主序：s[r + 4c]
    var t = s[13];
    s[13] = s[9];
    s[9] = s[5];
    s[5] = s[1];
    s[1] = t;

    t = s[2];
    s[2] = s[10];
    s[10] = t;
    t = s[6];
    s[6] = s[14];
    s[14] = t;

    t = s[3];
    s[3] = s[7];
    s[7] = s[11];
    s[11] = s[15];
    s[15] = t;
  }

  static void _invMixColumns(Uint8List s) {
    for (var c = 0; c < 4; c++) {
      final i = c * 4;
      final a0 = s[i], a1 = s[i + 1], a2 = s[i + 2], a3 = s[i + 3];
      s[i] = _mul0e[a0] ^ _mul0b[a1] ^ _mul0d[a2] ^ _mul09[a3];
      s[i + 1] = _mul09[a0] ^ _mul0e[a1] ^ _mul0b[a2] ^ _mul0d[a3];
      s[i + 2] = _mul0d[a0] ^ _mul09[a1] ^ _mul0e[a2] ^ _mul0b[a3];
      s[i + 3] = _mul0b[a0] ^ _mul0d[a1] ^ _mul09[a2] ^ _mul0e[a3];
    }
  }

  static void _addRoundKey(Uint8List s, Uint8List w, int round) {
    final off = round * 16;
    for (var i = 0; i < 16; i++) {
      s[i] ^= w[off + i];
    }
  }

  /// 解密**单个** 16 字节块（ECB 语义，CBC 的链式由调用方处理）。
  static void _decryptBlock(Uint8List block, Uint8List w) {
    _addRoundKey(block, w, 10);
    for (var round = 9; round >= 1; round--) {
      _invShiftRows(block);
      _invSubBytes(block);
      _addRoundKey(block, w, round);
      _invMixColumns(block);
    }
    _invShiftRows(block);
    _invSubBytes(block);
    _addRoundKey(block, w, 0);
  }

  // ── CBC 解密 ───────────────────────────────────────────────────────────

  /// AES-128-CBC 解密。
  ///
  /// [data] 必须为 16 的整数倍长度（HLS 分片天然满足）；否则返回 null
  /// （**不抛异常**——调用方据此安全退化，绝不因解密问题中断播放）。
  ///
  /// [iv] 为 16 字节初始向量；HLS 常用全零 IV（`IV=0x00...`）。
  ///
  /// 返回 [Uint8List]；长度非法或密钥非法时返回 null。
  static Uint8List? decrypt(
    Uint8List data,
    Uint8List key, {
    required Uint8List iv,
  }) {
    try {
      if (key.length != 16) return null;
      if (iv.length != 16) return null;
      if (data.isEmpty) return null;
      if (data.length % 16 != 0) return null;

      final w = _expandKey(key);
      final out = Uint8List(data.length);
      final block = Uint8List(16);

      // 🔴 性能修复（2026-10-12）：CBC 链式不再每块拷贝两份 16 字节缓冲。
      //
      // 【原先】每块 `Uint8List.fromList(block)` 复制一份密文用于下一块的
      //   XOR，300KB 分片 = 19130 块 ⇒ **38260 次小对象分配**，GC 压力大。
      //
      // 【现在】直接在输出缓冲 `out` 上做：`out` 先写密文原文，解密后原地
      //   XOR 成明文。下一块的「上一个密文块」就是 `out` 的前 16 字节
      //   —— 因为那时它还没被本块覆写？不成立，故改用：先把密文块读入
      //   `block`，解密后与 `prev` 异或写入 out；`prev` 复用同一个数组。
      //   全程只有 3 个固定缓冲，零每块分配。
      final prev = Uint8List.fromList(iv);

      for (var off = 0; off < data.length; off += 16) {
        // 1) 取本块密文（同时它就是下一块的 prev 源）
        for (var i = 0; i < 16; i++) {
          block[i] = data[off + i];
        }
        // 2) 块解密（原地）
        _decryptBlock(block, w);
        // 3) 与上一密文块异或得明文，并把本块密文存为下一块的 prev
        for (var i = 0; i < 16; i++) {
          out[off + i] = block[i] ^ prev[i];
          prev[i] = data[off + i];
        }
      }
      return out;
    } catch (_) {
      return null;
    }
  }
}
